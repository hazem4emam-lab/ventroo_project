import express from "express";
import cors from "cors";
import dotenv from "dotenv";

dotenv.config();

const app = express();

app.use(cors());
app.use(express.json());

app.get("/api/health", (req, res) => {
  res.status(200).json({ status: "ok" });
});

const PORT = 3000;;

app.listen(PORT, () => {
  console.log(`Ventro server running on port ${PORT}`);
});